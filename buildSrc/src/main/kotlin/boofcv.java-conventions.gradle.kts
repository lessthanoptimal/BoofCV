    listOf("annotationProcessor", "testAnnotationProcessor",
        "benchmarkAnnotationProcessor", "generateAnnotationProcessor").forEach {
        add(it, Libs.JABEL)
        // Even if it's not used you still need to include the dependency
        add(it, Libs.NULLAWAY)
    }

