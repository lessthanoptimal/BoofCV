/**
 * Shared configuration for every plain-Java BoofCV module. Applying this plugin is what
 * marks a project as one; the root aggregate tasks select modules by checking for it.
 */
plugins {
    `java-library`
    eclipse
    id("com.peterabeles.gversion")
    id("net.ltgt.errorprone")
    id("com.diffplug.spotless")
}

java {
    withJavadocJar()
    withSourcesJar()
    toolchain {
        languageVersion.set(JavaLanguageVersion.of(25))
        // Specify vendor to get around a GitHub Java 25 issue
        vendor.set(JvmVendorSpec.AZUL)
    }
}

// Run only once, in :main:autocode. See docs/AutoGeneratedCode.md
tasks.named("createVersionFile") { enabled = false }

sourceSets {
    create("benchmark") {
        java.srcDir("src/benchmark/java")
        resources.srcDir("src/benchmark/resources")
    }
    create("generate") {
        java.srcDir("src/generate/java")
        resources.srcDir("src/generate/resources")
    }
    create("experimental") {
        java.srcDir("src/experimental/java")
        resources.srcDir("src/experimental/resources")
    }
