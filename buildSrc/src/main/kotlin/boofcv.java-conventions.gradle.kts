// Expose these source sets so sibling modules can consume them without reaching into
// another project's `sourceSets`. Consumed as:
//     testImplementation(project(path = ":main:boofcv-ip", configuration = "testOutput"))
listOf("test", "benchmark", "generate", "experimental").forEach { sourceSet ->
    val output = configurations.create("${sourceSet}Output") {
        isCanBeConsumed = true
        isCanBeResolved = false
    }
    sourceSets[sourceSet].output.classesDirs.forEach { dir ->
        artifacts.add(output.name, dir) {
            builtBy(tasks.named("${sourceSet}Classes"))
        }
    }
}

// Prevents tons of errors if someone is using ASCII
tasks.withType<JavaCompile>().configureEach { options.encoding = "UTF-8" }

// Creates Java 11 byte code but Java 25 syntax
tasks.withType<JavaCompile>().configureEach {
    sourceCompatibility = "25"
    options.release.set(11)

    // Needed by ErrorProne
    options.compilerArgs.removeAll { it.startsWith("--should-stop=ifError") }
    options.compilerArgs.add("--should-stop=ifError=FLOW")

    // Enable incremental compile. Should make single file changes faster
    options.isIncremental = true
}

// For some reason examplesJar has a duplicate of ffmpeg pom
tasks.withType<Jar>().configureEach { duplicatesStrategy = DuplicatesStrategy.EXCLUDE }

// To make ErrorProne and Kotlin plugins happy, and fail on jar conflict
configurations.configureEach {
    resolutionStrategy {
        failOnVersionConflict()

        force(Libs.JETBRAINS_ANNOTATIONS)
        force(Libs.GUAVA)
        force(Libs.ERRORPRONE_ANNOTATIONS)
        force(Libs.JSR305)
        force(Libs.CHECKER_QUAL)
        force(Libs.COMMONS_LANG3)

        // Needed when updated to Java 25 and used by jabel
        force(Libs.BYTEBUDDY)
        force(Libs.BYTEBUDDY_AGENT)
    }
}

dependencies {
