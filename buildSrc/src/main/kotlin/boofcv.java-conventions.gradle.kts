tasks.named<Test>("test") {
    useJUnitPlatform()
    reports.html.required.set(false)
    // Several integration modules add an `examples` directory to their test source set
    // that holds sample code and no @Test classes.
    failOnNoDiscoveredTests = false
    // Make the error logging verbose to make debugging on CI easier
    testLogging {
        showStandardStreams = true
        exceptionFormat = TestExceptionFormat.FULL
        showCauses = true
        showExceptions = true
        showStackTraces = true
    }
}

tasks.named<Javadoc>("javadoc") {
    (options as StandardJavadocDocletOptions).apply {
        links(
            "https://docs.oracle.com/en/java/javase/11/docs/api/",
            "https://ejml.org/javadoc/",
            "https://ddogleg.org/javadoc/",
            "https://georegression.org/javadoc/"
        )
        // https://github.com/gradle/gradle/issues/11182 Error introduced in JDK 11
        addStringOption("-release", "11")
        addBooleanOption("html5", true)
    }
    isFailOnError = false
    // Disable to stop it from spamming stdout on snapshot builds
    enabled = !project.version.toString().contains("SNAPSHOT")
}

tasks.withType<JavaCompile>().configureEach {
    // Disabled for benchmarks, code generators, tests, and specific third party code.
    // boofcv-test is test infrastructure and is held to the same standard as tests.
    val skip = project.name.contains("ffmpeg") || project.name == "boofcv-test" ||
        name.startsWith("compileBenchmark") || name.startsWith("compileGenerate") ||
        name.startsWith("compileTest") || name.startsWith("compileExperimental")

    if (skip) {
        options.errorprone.isEnabled.set(false)
        return@configureEach
    }

    options.errorprone.isEnabled.set(true)
    options.errorprone.disableWarningsInGeneratedCode.set(true)
    options.errorprone.disable(
        "TypeParameterUnusedInFormals", "StringSplitter", "InconsistentCapitalization",
        "HidingField", // this is sometimes done when the specific type is known by child. Clean up later.
        "ClassNewInstance", // yes it's deprecated, but new version is more verbose with ignored errors
        "FloatingPointLiteralPrecision", // too many false positives in test code
        "EmptyCatch", // doesn't acknowledge "ignore". can't get the fix working. Should be an error
        "ReferenceEquality", // This is done intentionally a TON. Good test but not here
        "MutablePublicArray", // Done intentionally in every case
        "CatchAndPrintStackTrace", // Should clean up, but done too often right now
        "SameNameButDifferent", // Lombok confuses it
        "UnescapedEntity",
        "NarrowCalculation", // too many false positives where integer math is done intentionally
        "EmptyBlockTag", // E.g. "@param name" is not defined. This should be cleaned up
        "AlreadyChecked", // This inspection appears to be broken/too simplistic. False positives galore
        "EnumOrdinal", // This is used a LOT in GUI code
        "AssignmentExpression", // This pattern is used a fair amount and I'm not sure it's hard to read
    )
    options.errorprone.error(
        "MissingOverride", "MissingCasesInEnumSwitch", "BadInstanceof",
        "NarrowingCompoundAssignment", "JdkObsolete", "MissingSummary"
    )

    // Allow sloppy code where it's not published
    if (!name.endsWith("compileJava")) {
        options.errorprone.disable("MissingSummary")
    }

    options.errorprone.check("NullAway", CheckSeverity.ERROR)
    options.errorprone.option("NullAway:TreatGeneratedAsUnannotated", "true")
    options.errorprone.option("NullAway:AnnotatedPackages", "boofcv")
}

spotless {
    ratchetFrom("origin/SNAPSHOT")

    format("misc") {
        target("*.gradle", "*.gradle.kts", "*.md", ".gitignore")
        trimTrailingWhitespace()
        leadingSpacesToTabs()
        endWithNewline()
    }
    java {
        // There is currently no good way to exclude files that contain "@Generated" or are not
        // versions. This should catch most of them with a few false positives.
        target("**/java/boofcv/**/*.java")
        targetExclude("**/*_MT*.java", "**/*_F32.java", "**/generated/*")

        toggleOffOn("formatter:off", "formatter:on")
        // removeUnusedImports() <-- turned off due to a Java 25 issue
        endWithNewline()

        licenseHeaderFile("${project.rootDir}/misc/copyright.txt")
    }
}
