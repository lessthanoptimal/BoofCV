package boofcv.struct.convolve;

import org.ejml.MatrixFormattable;
import org.ejml.MatrixPrintFormat;

/**
 * Floating point 1D convolution kernel that extends {@link Kernel1D}.
 *
 * <p>
 * WARNING: Do not modify. Automatically generated by {@link boofcv.struct.convolve.GenerateKernel1D}.
 * </p>
 *
 * @author Peter Abeles
 */
@SuppressWarnings({"NullAway.Init"})
public class Kernel1D_S32 extends Kernel1D implements MatrixFormattable {

	public int[] data;

	/**
	 * Creates a new kernel whose initial values are specified by "data" and length is "width".
	 * The offset will be set to width/2
	 *
	 * @param width The kernel's width.
	 * @param data The value of the kernel. Not modified. Reference is not saved.
	 */
	public Kernel1D_S32( int width, int[] data ) {
		this(width, width/2, data);
	}

	/**
	 * Creates a kernel with elements equal to 'data' and with the specified 'width' plus 'offset'
	 *
	 * @param width The kernel's width.
	 * @param offset Location of the origin in the array
	 * @param data The value of the kernel. Not modified. Reference is not saved.
	 */
	public Kernel1D_S32( int width, int offset, int[] data ) {
		super(width, offset);

		this.data = new int[width];
		System.arraycopy(data, 0, this.data, 0, width);
	}

	/**
	 * Create a kernel with elements initialized to zero. Offset is automatically
	 * set to width/2.
	 *
	 * @param width How wide the kernel is.
	 */
	public Kernel1D_S32( int width ) {
		this(width, width/2);
	}

	/**
	 * Create a kernel whose elements initialized to zero.
	 *
	 * @param width How wide the kernel is.
	 * @param offset Location of the origin in the array
	 */
	public Kernel1D_S32( int width, int offset ) {
		super(width, offset);
		data = new int[width];
	}

	protected Kernel1D_S32() {}

	@Override
	public double getDouble( int index ) {
		return data[index];
	}

	@Override
	public void setD( int index, double value ) {
		data[index] = (int)value;
	}

	/**
	 * Creates a kernel whose elements are the specified data array and has
	 * the specified width.
	 *
	 * @param data The array who will be the kernel's data. Reference is saved.
	 * @param width The kernel's width.
	 * @param offset Location of the origin in the array
	 * @return A new kernel.
	 */
	public static Kernel1D_S32 wrap( int[] data, int width, int offset ) {
		Kernel1D_S32 ret = new Kernel1D_S32();
		ret.data = data;
		ret.width = width;
		ret.offset = offset;

		return ret;
	}

	@Override
	public Kernel1D_S32 copy() {
		Kernel1D_S32 ret = new Kernel1D_S32(width, offset);
		System.arraycopy(data, 0, ret.data, 0, ret.width);
		return ret;
	}

	@Override
	public boolean isInteger() {
		return true;
	}

	public int get( int i ) {
		return data[i];
	}

	public int computeSum() {
		int sum = 0;
		for (int i = 0; i < data.length; i++) {
			sum += data[i];
		}

		return sum;
	}

	@Override public String format( MatrixPrintFormat format ) {
		var builder = new StringBuilder();
		format.row(builder, width, ( col ) -> data[col]);
		return builder.toString();
	}

	public int[] getData() {
		return data;
	}

	/// How deep is the zero border around this kernel
	public int countZeroBorder() {
		for (int depth = 0; depth <= width/2; depth++) {
			if (get(depth) != 0)
				return depth;
			if (get(width - depth - 1) != 0)
				return depth;
		}
		// everything is zeros
		return width/2 + 1;
	}

	/// Removes the border up to the specified depth
	public Kernel1D_S32 trimBorder( int border ) {
		if (border <= 0)
			return this.copy();

		var out = new Kernel1D_S32(width - 2*border);
		out.offset = this.offset - border;
		for (int i = 0; i < out.width; i++) {
			out.data[i] = this.data[i + border];
		}
		return out;
	}

	public void print() {
		for (int i = 0; i < width; i++) {
			System.out.printf("%6d ", data[i]);
		}
		System.out.println();
	}

	@Override public String toString() {
		return getClass().getSimpleName() + " width=" + width + " offset=" + offset + "\n" + format();
	}

	public boolean isIdentical( Kernel1D_S32 a ) {
		if (a.width != width || a.offset != offset)
			return false;
		for (int i = 0; i < a.width; i++) {
			if (a.data[i] != data[i])
				return false;
		}
		return true;
	}
}
