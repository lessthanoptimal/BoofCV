plugins {
	id("boofcv.java-conventions")
}

dependencies {
	implementation(Libs.AUTOFLOAT)
	implementation(Libs.AUTOCONCURRENT)
	api(Libs.COMMONS_IO)
}

// The version file is generated here, once, rather than in every module.
tasks.named("createVersionFile") { enabled = true }

gversion {
	srcDir = "../boofcv-types/src/main/java"
	classPackage = "boofcv"
	className = "BoofVersion"
	annotate = "javax.annotation.Generated"
}

// Converts F64 code to F32 and generates the _MT concurrent implementations. Must run
// after the per-module `autogenerateSource` generators, since it uses their output as a
// template. See docs/AutoGeneratedCode.md
val autogenerateDerived by tasks.registering(JavaExec::class) {
	dependsOn("classes")
	dependsOn("createVersionFile")
	mainClass.set("boofcv.AutocodeMasterApp")
	classpath = sourceSets["main"].runtimeClasspath
}

// Forces the per-module source generators to run first
val autogenerateDep by tasks.registering {
	dependsOn(":main:boofcv-ip:autogenerateSource")
}

autogenerateDerived { mustRunAfter(autogenerateDep) }

// Invoking 'autogenerate' calls all project wide auto generation functions
tasks.register("autogenerate") {
	group = "build"
	description = "Runs every BoofCV code generator. Must be run before the first build."
	dependsOn(autogenerateDep)
	dependsOn(autogenerateDerived)
}
